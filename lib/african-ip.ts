export function getRandomAfricanIP(): string {
  const ranges: [number, number][] = [
    [41, 57],
    [41, 60],
    [41, 72],
    [41, 73],
    [41, 116],
    [41, 138],
    [41, 160],
    [41, 175],
    [41, 188],
    [41, 203],
    [41, 215],
    [41, 222],
    [102, 0],
    [102, 22],
    [102, 68],
    [102, 89],
    [102, 130],
    [102, 164],
    [102, 176],
    [102, 212],
    [105, 16],
    [105, 48],
    [105, 112],
    [105, 160],
    [105, 224],
    [197, 136],
    [197, 148],
    [197, 156],
    [197, 210],
    [197, 232],
    [197, 248],
    [45, 96],
    [45, 100],
    [45, 108],
  ];

  const base = ranges[Math.floor(Math.random() * ranges.length)];
  const rand = () => Math.floor(Math.random() * 254) + 1;

  return `${base[0]}.${base[1]}.${rand()}.${rand()}`;
}
